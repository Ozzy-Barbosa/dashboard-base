import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function navigate(page: Page, label: string) {
  if (await page.getByRole('button', { name: 'Abrir menú', exact: true }).isVisible())
    await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
  await page.getByRole('link', { name: label, exact: true }).filter({ visible: true }).click()
}
test.beforeEach(async ({ page }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Evolución de ingresos' })).toBeVisible()
})

test('resumen accesible, filtros coherentes y sin errores de consola', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  const first = await page.locator('.metric-value').first().textContent()
  await page.getByRole('combobox', { name: 'Período', exact: true }).selectOption('7')
  await expect(page.locator('.metric-value').first()).not.toHaveText(first!)
  await page.getByRole('combobox', { name: 'Canal de venta', exact: true }).selectOption('En línea')
  await expect(page.locator('.channel-list').getByText('$0', { exact: true })).toHaveCount(2)
  await expect(page.locator('body')).not.toContainText('NaN')
  const accessibility = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'])
    .analyze()
  expect(accessibility.violations).toEqual([])
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true
  )
})
test('ventas: búsqueda estable, vacío, paginación, orden y exportación', async ({ page }) => {
  await navigate(page, 'Ventas')
  await expect(page.locator('tbody tr')).toHaveCount(10)
  const first = await page.locator('tbody tr').first().textContent()
  await page.getByRole('button', { name: 'Página siguiente' }).click()
  await expect(page.locator('tbody tr').first()).not.toHaveText(first!)
  await page
    .getByRole('textbox', { name: 'Buscar ventas' })
    .pressSequentially('maria', { delay: 50 })
  await expect(page.getByRole('textbox', { name: 'Buscar ventas' })).toHaveValue('maria')
  await page.getByRole('textbox', { name: 'Buscar ventas' }).fill('ZZZNoExiste')
  await expect(page.getByRole('heading', { name: 'No encontramos ventas' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar búsqueda y estado' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(10)
  await page.getByRole('button', { name: 'Importe', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(10)
  const amounts = await page.locator('tbody .amount').allTextContents()
  expect(Number(amounts[0].replace(/[^\d.]/g, ''))).toBeGreaterThanOrEqual(
    Number(amounts[9].replace(/[^\d.]/g, ''))
  )
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar CSV' }).click()
  expect((await download).suggestedFilename()).toContain('pulso-ventas-comercio')
})
test('alta, actualización y persistencia de una venta sin duplicar ingresos', async ({ page }) => {
  await page.getByRole('button', { name: 'Nueva venta', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Nueva venta', exact: true })
  await modal.getByLabel('Nombre del cliente').fill('Prueba Navegador')
  await modal.getByLabel('Correo del cliente').fill('navegador@example.com')
  await modal.getByLabel('Total de la venta (MXN)').fill('1234.56')
  await modal.getByRole('combobox', { name: 'Estado', exact: true }).selectOption('Pendiente')
  await modal.getByRole('button', { name: 'Guardar venta' }).click()
  await expect(modal).not.toBeVisible()
  await navigate(page, 'Ventas')
  await page.getByRole('textbox', { name: 'Buscar ventas' }).fill('navegador@example.com')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: /^Ver venta/ }).click()
  await page.getByLabel('Actualizar estado').selectOption('Pagado')
  await page.getByRole('button', { name: 'Guardar estado' }).click()
  await expect(page.getByRole('dialog').locator('.status-badge')).toHaveText('Pagado')
  await page.getByRole('button', { name: 'Cerrar ventana', exact: true }).click()
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.locator('tbody .amount')).toHaveText('$1,234.56')
  await expect(page.locator('tbody .status-badge')).toHaveText('Pagado')
})
