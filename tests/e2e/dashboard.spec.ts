test('preferencias, tema oscuro, búsqueda por teclado y navegación al recargar', async ({
  page,
}) => {
  await navigate(page, 'Configuración')
  await page.getByLabel('Nombre visible').fill('Negocio de prueba')
  await page.getByLabel('Oscuro', { exact: true }).check()
  await page.getByRole('button', { name: 'Guardar preferencias' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.getByLabel('Nombre visible')).toHaveValue('Negocio de prueba')
  const accessibility = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'])
    .analyze()
  expect(accessibility.violations).toEqual([])
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('dialog', { name: 'Buscar en Pulso' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
